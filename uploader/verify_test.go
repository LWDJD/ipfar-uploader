// buildCBORFormatCAR builds a minimal CAR v2 file using the standard CBOR pragma
// and CBOR-format v1 header (as go-car/v2 would generate). Returns the CAR bytes
// and the root CID.
func buildCBORFormatCAR(t *testing.T) ([]byte, cid.Cid) {
	t.Helper()

	// We build a valid CAR v1 block then wrap it in CBOR-format v2.
	// Use the uploader's builder to get a valid root CID and data block,
	// then re-encode using CBOR format.

	builder := car.NewCarV2Builder()
	rootCID, err := builder.AddRawBlock([]byte("hello cbor car v2"))
	if err != nil {
		t.Fatalf("AddRawBlock failed: %v", err)
	}

	// Manually encode the data block
	rootCIDBytes := rootCID.Bytes()
	blockData := []byte("hello cbor car v2")
	sectionLen := uint64(len(rootCIDBytes) + len(blockData))

	var dataBuf bytes.Buffer
	// varint(sectionLen)
	dataBuf.Write(encodeVarint(sectionLen))
	// CID bytes
	dataBuf.Write(rootCIDBytes)
	// block data
	dataBuf.Write(blockData)

	// Build CBOR v1 header:
	// {"roots": [<CID>], "version": 1}
	cborContent := buildCBORV1Header(rootCIDBytes)

	// CBOR v1 header: varint(CBOR length) + CBOR data
	v1HeaderBytes := append(encodeVarint(uint64(len(cborContent))), cborContent...)

	// Build CBOR v2 pragma + header
	// Standard pragma: 0x0a (uint(10) — outer CBOR length), then CBOR: {"version": 2}
	cborPragma := []byte{
		0x0a,                                           // uint(10) — outer CBOR map length
		0xa1,                                           // map(1)
		0x67,                                           // string(7)
		0x76, 0x65, 0x72, 0x73, 0x69, 0x6f, 0x6e, // "version"
		0x02,                                           // uint(2)
	}

	// Standard v2 header (40 bytes): Characteristics[16] + DataOffset[8] + DataSize[8] + IndexOffset[8]
	pragmaLen := uint64(len(cborPragma))
	v2HeaderLen := uint64(40)
	v1HeaderLen := uint64(len(v1HeaderBytes))
	dataOffset := pragmaLen + v2HeaderLen
	dataSize := v1HeaderLen + uint64(dataBuf.Len())
	indexOffset := dataOffset + dataSize

	// Build a minimal valid index
	indexEntryContent := append(encodeVarint(uint64(len(rootCIDBytes))), rootCIDBytes...)
	indexEntryContent = append(indexEntryContent, encodeVarint(v1HeaderLen)...)
	indexBuf := append(encodeVarint(uint64(len(indexEntryContent))), indexEntryContent...)
	// Pad to 8 bytes
	padLen := (8 - (len(indexBuf) % 8)) % 8
	for i := 0; i < padLen; i++ {
		indexBuf = append(indexBuf, 0)
	}
	indexSize := uint64(len(indexBuf))

	v2Header := make([]byte, 40)
	// Characteristics [0:16] — all zeros
	binary.LittleEndian.PutUint64(v2Header[16:24], dataOffset)
	binary.LittleEndian.PutUint64(v2Header[24:32], dataSize)
	binary.LittleEndian.PutUint64(v2Header[32:40], indexOffset)

	var carBuf bytes.Buffer
	carBuf.Write(cborPragma)
	carBuf.Write(v2Header)
	carBuf.Write(v1HeaderBytes)
	carBuf.Write(dataBuf.Bytes())
	carBuf.Write(indexBuf)

	result := carBuf.Bytes()

	_ = indexSize
	_ = result

	return result, rootCID
}

// buildCBORV1Header builds the CBOR content for a CAR v1 header.
// Format: {"roots": [<CID>], "version": 1}
func buildCBORV1Header(cidBytes []byte) []byte {
	// CID bytes with multibase identity prefix (0x00)
	cidWithPrefix := append([]byte{0x00}, cidBytes...)

	var buf bytes.Buffer

	// map(2)
	buf.WriteByte(0xa2)

	// key: "roots" (string of length 5)
	buf.WriteByte(0x65)
	buf.WriteString("roots")

	// value: array(1)
	buf.WriteByte(0x81)
	//   tag(42)
	buf.WriteByte(0xd8)
	buf.WriteByte(0x2a)
	//   bytes(35)
	buf.WriteByte(0x58)
	buf.WriteByte(byte(len(cidWithPrefix)))
	buf.Write(cidWithPrefix)

	// key: "version" (string of length 7)
	buf.WriteByte(0x67)
	buf.WriteString("version")

	// value: uint(1)
	buf.WriteByte(0x01)

	return buf.Bytes()
}

// encodeVarint encodes a uint64 as a varint byte slice.
func encodeVarint(v uint64) []byte {
	if v < 128 {
		return []byte{byte(v)}
	}
	var buf []byte
	for v >= 128 {
		buf = append(buf, byte(v)|0x80)
		v >>= 7
	}
	buf = append(buf, byte(v))
	return buf
}
