// newMockGateway starts an HTTP test server that serves the given CAR bytes
// (with proper Range support) and returns a GatewayClient pointed at it.
func newMockGateway(t *testing.T, carBytes []byte) (*arweave.GatewayClient, string, func()) {
	t.Helper()

	mux := http.NewServeMux()
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		// Support HEAD for file size
		if r.Method == http.MethodHead {
			w.Header().Set("Content-Length", fmt.Sprintf("%d", len(carBytes)))
			w.WriteHeader(http.StatusOK)
			return
		}

		// Support Range requests
		rangeHeader := r.Header.Get("Range")
		if rangeHeader != "" {
			var start, end int64
			_, err := fmt.Sscanf(rangeHeader, "bytes=%d-%d", &start, &end)
			if err != nil {
				// Try "bytes=%d-" format
				_, err = fmt.Sscanf(rangeHeader, "bytes=%d-", &start)
				if err != nil {
					w.WriteHeader(http.StatusBadRequest)
					return
				}
				end = int64(len(carBytes)) - 1
			}

			if start >= int64(len(carBytes)) {
				w.WriteHeader(http.StatusRequestedRangeNotSatisfiable)
				return
			}
			if end >= int64(len(carBytes)) {
				end = int64(len(carBytes)) - 1
			}

			w.Header().Set("Content-Range",
				fmt.Sprintf("bytes %d-%d/%d", start, end, len(carBytes)))
			w.Header().Set("Content-Length", fmt.Sprintf("%d", end-start+1))
			w.WriteHeader(http.StatusPartialContent)
			w.Write(carBytes[start : end+1])
			return
		}

		// Full response
		w.Header().Set("Content-Length", fmt.Sprintf("%d", len(carBytes)))
		w.WriteHeader(http.StatusOK)
		w.Write(carBytes)
	})

	server := httptest.NewServer(mux)
	client := arweave.NewGatewayClient(server.URL)

	// The gateway client expects the URL to not have a trailing slash,
	// and DownloadTransactionDataRange appends "/{txID}".
	// Our mock uses "/" as catch-all, so any txID works.
	txID := "mock-tx-id"

	cleanup := func() {
		server.Close()
	}

	return client, txID, cleanup
}

// TestVerifyRemoteCAR_LegacyFormat tests that VerifyRemoteCAR correctly
// validates a CAR v2 file generated by the uploader's own builder (which
// uses the legacy "car\x02" pragma and varint-format v1 header).
func TestVerifyRemoteCAR_LegacyFormat(t *testing.T) {
	// Build a CAR v2 file locally
	carBytes, rootCID, err := car.CreateCarV2FromBytes([]byte("hello world test data"))
	if err != nil {
		t.Fatalf("failed to create CAR v2: %v", err)
	}
	_ = carBytes

	gateway, txID, cleanup := newMockGateway(t, carBytes)
	defer cleanup()

	verified, err := VerifyRemoteCAR(context.Background(), gateway, txID, rootCID.String())
	if err != nil {
		t.Fatalf("VerifyRemoteCAR failed: %v", err)
	}
	if !verified {
		t.Fatal("expected verified=true, got false")
	}
}

